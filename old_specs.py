REGION_COLS = ("アジア州", "ヨーロッパ州", "アフリカ州", "北アメリカ州", "南アメリカ州", "オセアニア州")


def nat_spec(pages):
    """都道府県×国籍の表の形。pages はページごとの [左の列, 右の列]（左の最初は「総数」）。
    確かめ：州の列＝その州の国の合計、総数＝州の列の合計＋無国籍"""
    names = [c for pg in pages for side in pg for c in side]
    checks, cur, members = [], None, []
    for c in names[1:]:
        if c in REGION_COLS:
            if cur:
                checks.append((cur, members))
            cur, members = c, []
        elif c != "無国籍":
            members.append(c)
    if cur:
        checks.append((cur, members))
    checks.append(("総数", [c for c in names if c in REGION_COLS] + (["無国籍"] if "無国籍" in names else [])))
    return {"rows": ROWS_48, "pages": pages, "checks": checks, "total_row": "総数"}


