def pref_rows(splits, okinawa=True, pref_total=False):
    """都道府県の行の並び。splits={"東京都": ["特別区", "その他"], …} は大きな市の内わけの行。
    pref_total=True なら内わけの前に都道府県の合計の行もある"""
    out = ["総数"]
    for p in PREFS:
        if p == "沖縄県" and not okinawa:
            continue
        if p in splits:
            if pref_total:
                out.append(p)
            out += [f"{p}:{s}" for s in splits[p]]
        else:
            out.append(p)
    return out


def pairs(codes, a="旅券あり", b="旅券なし"):
    return [f"{c}（{x}）" for c in codes for x in (a, b)]


